"""Writes review reports to disk and posts them as GitHub commit comments."""

from __future__ import annotations

import logging
from pathlib import Path

import requests

from agent.config import Settings

log = logging.getLogger(__name__)

# GitHub rejects comment bodies longer than 65536 characters.
MAX_COMMENT_CHARS = 60000


def format_report(sha: str, files: list[str], body: str) -> str:
    file_list = ", ".join(f"`{f}`" for f in files) or "none"
    return (
        f"# AI code review for `{sha[:10]}`\n\n"
        f"Files reviewed: {file_list}\n\n"
        f"{body.strip()}\n\n"
        "---\n_Generated by AI Agent Monitor (OpenCode + pylint)._\n"
    )


def write_report(settings: Settings, sha: str, content: str) -> Path:
    settings.reports_dir.mkdir(parents=True, exist_ok=True)
    path = settings.reports_dir / f"{sha[:10]}.md"
    path.write_text(content, encoding="utf-8")
    log.info("Wrote report %s", path)
    return path


def post_commit_comment(settings: Settings, sha: str, content: str) -> str | None:
    """Post the review on the commit. Returns the comment URL, or None if no token is set."""
    if settings.github_token is None:
        log.info("GITHUB_TOKEN not set; skipping commit comment")
        return None
    if len(content) > MAX_COMMENT_CHARS:
        content = content[:MAX_COMMENT_CHARS] + "\n\n_Review truncated; see the full report._\n"

    url = f"{settings.github_api_base}/repos/{settings.github_repo}/commits/{sha}/comments"
    response = requests.post(
        url,
        json={"body": content},
        headers={
            "Authorization": f"Bearer {settings.github_token.get_secret_value()}",
            "Accept": "application/vnd.github+json",
        },
        timeout=30,
    )
    response.raise_for_status()
    comment_url = response.json().get("html_url")
    log.info("Posted commit comment %s", comment_url)
    return comment_url
